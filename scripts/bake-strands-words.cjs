// Bakes src/components/strandsWords.ts: every word in scripts/english-words.txt (3+ letters) that can be traced on the
// Strands board (StrandsGame.tsx), i.e. along neighbouring letters (diagonals included) without reusing one.
// Those are the only words a player can ever spell, so the game checks against this short list instead of loading the
// whole 1.7 MB dictionary. Re-run after changing the board: node scripts/bake-strands-words.cjs
const fs = require('fs')
const path = require('path')
const root = path.join(__dirname, '..')
const src = fs.readFileSync(path.join(root, 'src/components/StrandsGame.tsx'), 'utf8')
const COLS = Number(src.match(/const COLS = (\d+)/)[1])
const letters = []
for (const m of src.matchAll(/word: "([A-Z]+)"[^\n]*?cells: (\[\[.*?\]\])/g)) {
  JSON.parse(m[2]).forEach(([r, c], i) => (letters[r * COLS + c] = m[1][i]))
}
const n = letters.length
if (letters.some((l) => !l)) throw new Error('board has holes')
const adjacent = (a, b) =>
  a !== b && Math.abs(Math.floor(a / COLS) - Math.floor(b / COLS)) <= 1 && Math.abs((a % COLS) - (b % COLS)) <= 1
const words = fs.readFileSync(path.join(root, 'scripts/english-words.txt'), 'utf8').split('\n').map((w) => w.trim()).filter((w) => w.length >= 3)
const trie = {}
for (const w of words) {
  let t = trie
  for (const ch of w.toUpperCase()) t = t[ch] ??= {}
  t.$ = w
}
const found = new Set()
const used = new Array(n).fill(false)
const walk = (cell, t) => {
  const next = t[letters[cell]]
  if (!next) return
  if (next.$) found.add(next.$)
  used[cell] = true
  for (let j = 0; j < n; j++) if (!used[j] && adjacent(cell, j)) walk(j, next)
  used[cell] = false
}
for (let i = 0; i < n; i++) walk(i, trie)
const list = [...found].sort()
fs.writeFileSync(
  path.join(root, 'src/components/strandsWords.ts'),
  `// Generated by scripts/bake-strands-words.cjs: the dictionary words that can be traced on the Strands board. Do not edit.\n` +
    `export const BOARD_WORDS = new Set(${JSON.stringify(list.join(' '))}.split(' '))\n`,
)
console.log(`${list.length} traceable words`)
